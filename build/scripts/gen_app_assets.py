"""Phase 3 helper - generate the Flutter app's assets FROM the build artifacts.

  .venv/bin/python build/scripts/gen_app_assets.py

Writes (all derived, no hand-typed values):
  * app/assets/models/model_meta.json  - app schema (labels=display labels with the raw
    typo fixed, mean/std/input size/threshold from build/model_meta.json, temperature=1.0
    because temperature scaling is NOT applied, sourced from model_card.json)
  * app/assets/ui_strings.json         - verbatim copy of build/ui_strings.json
  * app/assets/models/tomatoguard.tflite - copy of the exported TFLite file (sha-checked)

Target dir: tomatoguard/app/assets/ (existing Flutter project). Restart-proof (idempotent).
"""
from __future__ import annotations

import hashlib
import json
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILD = ROOT / "build"
APP_ASSETS = ROOT / "tomatoguard" / "app" / "assets"


def main() -> int:
    meta = json.loads((BUILD / "model_meta.json").read_text())
    card = json.loads((BUILD / "model_card.json").read_text())
    tfl_src = ROOT / meta["model_files"]["tflite"]
    if not tfl_src.exists():
        # fall back to the canonical export path (Phase 1 may name it either way)
        tfl_src = BUILD / "models" / "leaf_mobilenet_v3_large_seed42.tflite"
    if not tfl_src.exists():
        print("FATAL: TFLite model missing - run export_tflite.py + parity_tflite.py first",
              file=sys.stderr)
        return 3

    APP_ASSETS.mkdir(parents=True, exist_ok=True)
    (APP_ASSETS / "models").mkdir(exist_ok=True)

    app_meta = {
        "_comment": "GENERATED by build/scripts/gen_app_assets.py from build/model_meta.json "
                   "- do not hand-edit. temperature=1.0 means temperature scaling is NOT applied.",
        "labels": meta["display_labels"],
        "input_size": meta["input_size"][0],
        "mean": meta["mean"],
        "std": meta["std"],
        "temperature": 1.0 if not card["calibration"]["temperature_scaling_applied"]
                       else card["calibration"].get("fitted_temperature", 1.0),
        "uncertain_threshold": meta["threshold"],
        "healthy_label": "Healthy" if "Healthy" in meta["display_labels"] else None,
        "not_tomato_label": None,
        "model_version": meta["model_version"],
        "sha256": meta["sha256"].get("tflite"),
        "source": "build/model_meta.json",
    }
    (APP_ASSETS / "model_meta_tmp.json")  # ensure dir exists (mkdir above covers it)
    (APP_ASSETS / "models" / "model_meta.json").write_text(json.dumps(app_meta, indent=2))

    ui_src = BUILD / "ui_strings.json"
    shutil.copyfile(ui_src, APP_ASSETS / "ui_strings.json")
    mc = BUILD / "model_card.json"
    if mc.exists():
        shutil.copyfile(mc, APP_ASSETS / "model_card.json")

    dst = APP_ASSETS / "models" / "tomatoguard.tflite"
    if not dst.exists() or hashlib.sha256(dst.read_bytes()).hexdigest() != \
            hashlib.sha256(tfl_src.read_bytes()).hexdigest():
        shutil.copyfile(tfl_src, dst)
    assert hashlib.sha256(dst.read_bytes()).hexdigest() == hashlib.sha256(
        tfl_src.read_bytes()).hexdigest(), "tflite copy sha mismatch"

    print(f"wrote {APP_ASSETS / 'models' / 'model_meta.json'}, "
          f"ui_strings.json, tomatoguard.tflite "
          f"({dst.stat().st_size} bytes, threshold={app_meta['uncertain_threshold']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
